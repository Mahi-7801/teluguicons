-- ========== TICKETS (Configuration per session & tier) ==========
CREATE TABLE IF NOT EXISTS public.tickets (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session         SMALLINT NOT NULL CHECK (session IN (1, 2)),  -- 1 = 10AM-2PM, 2 = 3PM-7PM
  tier            VARCHAR(10) NOT NULL CHECK (tier IN ('vvip', 'mip')),
  price_paisa     INT NOT NULL,  -- price in paise (50000 = ₹500)
  inventory       INT NOT NULL DEFAULT 0,  -- admin-only, never exposed publicly
  sold            INT NOT NULL DEFAULT 0,
  availability    VARCHAR(20) NOT NULL DEFAULT 'available' CHECK (availability IN ('available','filling_fast','almost_sold_out','sold_out')),
  is_active       SMALLINT NOT NULL DEFAULT 1,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (session, tier)
);

-- ========== TICKET ORDERS ==========
CREATE TABLE IF NOT EXISTS public.ticket_orders (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code          VARCHAR(30) NOT NULL UNIQUE,
  ticket_id           INT NOT NULL REFERENCES public.tickets(id),
  session             SMALLINT NOT NULL,
  tier                VARCHAR(10) NOT NULL,
  quantity            SMALLINT NOT NULL DEFAULT 1,
  price_paisa         INT NOT NULL,
  buyer_name          VARCHAR(190) NOT NULL,
  buyer_email         VARCHAR(150) NOT NULL,
  buyer_phone         VARCHAR(30) NOT NULL,
  payment_status      VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending','paid','failed','refunded')),
  payment_reference   VARCHAR(120) NULL,
  qr_token            VARCHAR(64) NOT NULL UNIQUE,
  is_checked_in       SMALLINT NOT NULL DEFAULT 0,
  checked_in_at       TIMESTAMPTZ NULL,
  food_entitlement    VARCHAR(20) NOT NULL DEFAULT 'lunch',  -- 'lunch' or 'dinner'
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ticket_orders_phone ON public.ticket_orders (buyer_phone);
CREATE INDEX IF NOT EXISTS idx_ticket_orders_status ON public.ticket_orders (payment_status);
CREATE INDEX IF NOT EXISTS idx_ticket_orders_qr ON public.ticket_orders (qr_token);

