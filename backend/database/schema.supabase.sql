-- ========== USERS (Admins) ==========
CREATE TABLE IF NOT EXISTS public.users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(120) NOT NULL,
  email         VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(20) NOT NULL DEFAULT 'admin',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ========== CATEGORIES ==========
CREATE TABLE IF NOT EXISTS public.categories (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(190) NOT NULL,
  slug        VARCHAR(200) NOT NULL UNIQUE,
  type        VARCHAR(30) NOT NULL DEFAULT 'self_nomination',
  description TEXT NULL,
  icon        VARCHAR(50) NULL,
  sort_order  INT NOT NULL DEFAULT 0,
  voting_open SMALLINT NOT NULL DEFAULT 1,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_categories_type ON public.categories (type);
CREATE INDEX IF NOT EXISTS idx_categories_sort ON public.categories (sort_order);

-- ========== NOMINEES ==========
CREATE TABLE IF NOT EXISTS public.nominees (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id     INT NOT NULL REFERENCES public.categories(id) ON DELETE CASCADE,
  full_name       VARCHAR(190) NOT NULL,
  slug            VARCHAR(210) NOT NULL UNIQUE,
  bio             TEXT NULL,
  photo_url       VARCHAR(500) NULL,
  social_handle   VARCHAR(190) NULL,
  followers_count BIGINT NULL DEFAULT 0,
  featured        SMALLINT NOT NULL DEFAULT 0,
  status          VARCHAR(20) NOT NULL DEFAULT 'pending',
  nominee_code    VARCHAR(20) NULL UNIQUE,
  vote_count      INT NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_nominees_category ON public.nominees (category_id);
CREATE INDEX IF NOT EXISTS idx_nominees_status ON public.nominees (status);
CREATE INDEX IF NOT EXISTS idx_nominees_featured ON public.nominees (featured);

-- ========== NOMINATIONS ==========
CREATE TABLE IF NOT EXISTS public.nominations (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id      INT NOT NULL REFERENCES public.categories(id) ON DELETE CASCADE,
  nomination_code  VARCHAR(20) NULL UNIQUE,
  full_name        VARCHAR(190) NOT NULL,
  creator_name     VARCHAR(190) NULL,
  email            VARCHAR(150) NULL,
  phone            VARCHAR(30) NULL,
  city             VARCHAR(120) NULL,
  state            VARCHAR(120) NULL,
  primary_platform VARCHAR(60) NULL,
  youtube_url      VARCHAR(500) NULL,
  instagram_url    VARCHAR(500) NULL,
  facebook_url     VARCHAR(500) NULL,
  other_profile_url VARCHAR(500) NULL,
  website_url      VARCHAR(500) NULL,
  photo_url        VARCHAR(500) NULL,
  journey          TEXT NULL,
  achievements     TEXT NULL,
  support_links    TEXT NULL,
  status           VARCHAR(20) NOT NULL DEFAULT 'pending',
  admin_notes      TEXT NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_nominations_status ON public.nominations (status);
CREATE INDEX IF NOT EXISTS idx_nominations_category ON public.nominations (category_id);
CREATE INDEX IF NOT EXISTS idx_nominations_code ON public.nominations (nomination_code);

-- ========== OTP SESSIONS ==========
CREATE TABLE IF NOT EXISTS public.otp_sessions (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mobile     VARCHAR(20) NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  purpose    VARCHAR(30) NOT NULL DEFAULT 'vote',
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_otp_mobile ON public.otp_sessions (mobile);
CREATE INDEX IF NOT EXISTS idx_otp_token ON public.otp_sessions (token_hash);
CREATE INDEX IF NOT EXISTS idx_otp_expires ON public.otp_sessions (expires_at);

-- ========== VOTES (one per category per phone / email / device) ==========
CREATE TABLE IF NOT EXISTS public.votes (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nominee_id         INT NOT NULL REFERENCES public.nominees(id) ON DELETE CASCADE,
  category_id        INT NOT NULL REFERENCES public.categories(id) ON DELETE CASCADE,
  voter_name         VARCHAR(120) NULL,
  voter_email        VARCHAR(150) NULL,
  voter_phone        VARCHAR(30) NULL,
  ip_address         VARCHAR(60) NULL,
  user_agent         VARCHAR(300) NULL,
  otp_verified       SMALLINT NOT NULL DEFAULT 0,
  verification_token VARCHAR(64) NULL,
  device_fingerprint VARCHAR(64) NULL,
  is_flagged         SMALLINT NOT NULL DEFAULT 0,
  flag_reason        VARCHAR(255) NULL,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_votes_nominee ON public.votes (nominee_id);
CREATE INDEX IF NOT EXISTS idx_votes_category ON public.votes (category_id);
CREATE INDEX IF NOT EXISTS idx_votes_flagged ON public.votes (is_flagged);
CREATE INDEX IF NOT EXISTS idx_votes_created ON public.votes (created_at);
CREATE INDEX IF NOT EXISTS idx_votes_fingerprint ON public.votes (device_fingerprint);
CREATE INDEX IF NOT EXISTS idx_votes_ip ON public.votes (ip_address);
CREATE UNIQUE INDEX IF NOT EXISTS uq_votes_category_phone ON public.votes (category_id, voter_phone);
CREATE UNIQUE INDEX IF NOT EXISTS uq_votes_category_email ON public.votes (category_id, voter_email);
CREATE UNIQUE INDEX IF NOT EXISTS uq_votes_category_device ON public.votes (category_id, device_fingerprint);
CREATE INDEX IF NOT EXISTS idx_votes_category_ip ON public.votes (category_id, ip_address, user_agent);

-- ========== SPONSORS ==========
CREATE TABLE IF NOT EXISTS public.sponsors (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(190) NOT NULL,
  tier        VARCHAR(30) NOT NULL DEFAULT 'gold',
  logo_url    VARCHAR(500) NULL,
  website_url VARCHAR(300) NULL,
  tagline     VARCHAR(255) NULL,
  is_active   SMALLINT NOT NULL DEFAULT 1,
  sort_order  INT NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_sponsors_tier ON public.sponsors (tier);
CREATE INDEX IF NOT EXISTS idx_sponsors_active ON public.sponsors (is_active);

-- ========== SETTINGS ==========
CREATE TABLE IF NOT EXISTS public.settings (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key   VARCHAR(120) NOT NULL UNIQUE,
  setting_value TEXT NULL,
  group_name    VARCHAR(80) NOT NULL DEFAULT 'general',
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ========== CONTACT MESSAGES ==========
CREATE TABLE IF NOT EXISTS public.contact_messages (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(120) NOT NULL,
  email      VARCHAR(150) NOT NULL,
  phone      VARCHAR(30) NULL,
  subject    VARCHAR(190) NULL,
  message    TEXT NOT NULL,
  is_read    SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ========== SMS SENDERS / TEMPLATES ==========
CREATE TABLE IF NOT EXISTS public.sms_senders (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id  VARCHAR(20) NOT NULL UNIQUE,
  name       VARCHAR(120) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sms_templates (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            VARCHAR(120) NOT NULL,
  sender_id       VARCHAR(20) NOT NULL,
  dlt_template_id VARCHAR(120) NOT NULL,
  content         TEXT NULL,
  template_type   VARCHAR(30) NOT NULL DEFAULT 'otp',
  is_active       SMALLINT NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_sms_templates_active ON public.sms_templates (is_active);

-- ========== updated_at auto-triggers (replaces MySQL ON UPDATE) ==========
CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['users','nominees','nominations','settings','sms_templates']
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%s_updated ON public.%I', t, t);
    EXECUTE format('CREATE TRIGGER trg_%s_updated BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', t, t);
  END LOOP;
END $$;

-- ========== Row Level Security: allow ALL access via service_role/api.
-- The API uses the service_role key (or anon if you enable it), so RLS is
-- disabled by default here. If you harden later, add proper policies.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nominees ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nominations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.otp_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.votes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sponsors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sms_senders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sms_templates ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='users') THEN
    CREATE POLICY allow_all_users ON public.users FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_categories ON public.categories FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_nominees ON public.nominees FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_nominations ON public.nominations FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_otp_sessions ON public.otp_sessions FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_votes ON public.votes FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_sponsors ON public.sponsors FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_settings ON public.settings FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_contact_messages ON public.contact_messages FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_sms_senders ON public.sms_senders FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY allow_all_sms_templates ON public.sms_templates FOR ALL USING (true) WITH CHECK (true);
  END IF;
END $$;

