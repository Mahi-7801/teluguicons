-- ========== 1. Nominee profile completeness ==========
-- Achievements and real social URLs used to be collapsed into `bio` /
-- `social_handle` at promotion time. Keep them as first-class fields so the
-- nominee page can render them (add-on requirement 2).
ALTER TABLE public.nominees ADD COLUMN IF NOT EXISTS achievements TEXT NULL;
ALTER TABLE public.nominees ADD COLUMN IF NOT EXISTS youtube_url   VARCHAR(500) NULL;
ALTER TABLE public.nominees ADD COLUMN IF NOT EXISTS instagram_url VARCHAR(500) NULL;
ALTER TABLE public.nominees ADD COLUMN IF NOT EXISTS facebook_url  VARCHAR(500) NULL;
ALTER TABLE public.nominees ADD COLUMN IF NOT EXISTS website_url   VARCHAR(500) NULL;
ALTER TABLE public.nominees ADD COLUMN IF NOT EXISTS other_profile_url VARCHAR(500) NULL;

-- Link a nominee back to the nomination it came from. Makes re-shortlisting a
-- nomination idempotent (it updates the existing nominee instead of creating a
-- second one with a different slug).
ALTER TABLE public.nominees ADD COLUMN IF NOT EXISTS nomination_id INT NULL REFERENCES public.nominations(id) ON DELETE SET NULL;

-- ========== 2. Sequential internal nominee ID (TIC26-00001) ==========
-- Public URLs use the readable slug; the database uses this unique internal
-- ID so two nominees with the same name never collide (add-on req. 4).
CREATE SEQUENCE IF NOT EXISTS public.nominee_code_seq START 1 INCREMENT 1;

ALTER SEQUENCE public.nominee_code_seq RESTART WITH 1;

CREATE OR REPLACE FUNCTION public.next_nominee_code() RETURNS VARCHAR(20)
LANGUAGE plpgsql AS $$
BEGIN
  RETURN 'TIC26-' || LPAD(NEXTVAL('public.nominee_code_seq')::TEXT, 5, '0');
END;
$$;

-- Existing rows keep whatever code they already have; new rows get one
-- automatically. The backend can also request a code explicitly.
ALTER TABLE public.nominees ALTER COLUMN nominee_code SET DEFAULT public.next_nominee_code();

-- Keep the sequence ahead of any codes that were assigned before this ran.
DO $$
DECLARE
  max_seq INTEGER;
BEGIN
  SELECT COALESCE(MAX(NULLIF(regexp_replace(nominee_code, '\D', '', 'g'), '')::INTEGER), 0)
    INTO max_seq
    FROM public.nominees
   WHERE nominee_code ~ '^TIC26-\d+$';
  IF max_seq > 0 THEN
    PERFORM setval('public.nominee_code_seq', GREATEST(max_seq, (SELECT last_value FROM public.nominee_code_seq)));
  END IF;
END $$;

-- A nomination can only ever produce one nominee.
CREATE UNIQUE INDEX IF NOT EXISTS uq_nominees_nomination ON public.nominees (nomination_id) WHERE nomination_id IS NOT NULL;

-- ========== 3. Nominee campaign analytics ==========
-- Add-on req. 14: page views, voting-page clicks, share clicks, QR scans.
-- Conversions are not stored here - they are counted from the `votes` table so
-- they can never disagree with the real tally.
CREATE TABLE IF NOT EXISTS public.nominee_campaign_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nominee_id  INT NOT NULL REFERENCES public.nominees(id) ON DELETE CASCADE,
  event_type  VARCHAR(30) NOT NULL,
  source      VARCHAR(60) NULL,
  referrer    VARCHAR(300) NULL,
  fingerprint VARCHAR(64) NULL,
  ip_address  VARCHAR(60) NULL,
  user_agent  VARCHAR(300) NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_campaign_events_nominee ON public.nominee_campaign_events (nominee_id);
CREATE INDEX IF NOT EXISTS idx_campaign_events_type ON public.nominee_campaign_events (event_type);
CREATE INDEX IF NOT EXISTS idx_campaign_events_created ON public.nominee_campaign_events (created_at);
CREATE INDEX IF NOT EXISTS idx_campaign_events_dedupe ON public.nominee_campaign_events (nominee_id, event_type, fingerprint, created_at DESC);

ALTER TABLE public.nominee_campaign_events ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='nominee_campaign_events') THEN
    CREATE POLICY allow_all_campaign_events ON public.nominee_campaign_events FOR ALL USING (true) WITH CHECK (true);
  END IF;
END $$;

-- Retention: campaign events are aggregate-only, no voter data is kept here,
-- so old rows can be pruned freely. Keeps the table from growing forever.
-- (Run manually, e.g. monthly:  DELETE FROM public.nominee_campaign_events
--                                 WHERE created_at < NOW() - INTERVAL '18 months';)

-- ========== 4. Sponsorship slots ==========
-- Add-on req. 20: sponsor branding must be addable later without rebuilding the
-- nominee pages, without the nominee page reading sponsor tables today.
CREATE TABLE IF NOT EXISTS public.sponsor_slots (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot_key   VARCHAR(60) NOT NULL UNIQUE,
  label      VARCHAR(120) NULL,
  sponsor_id INT NULL REFERENCES public.sponsors(id) ON DELETE SET NULL,
  is_active  SMALLINT NOT NULL DEFAULT 1,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trg_sponsor_slots_updated ON public.sponsor_slots;
CREATE TRIGGER trg_sponsor_slots_updated BEFORE UPDATE ON public.sponsor_slots
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.sponsor_slots ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='sponsor_slots') THEN
    CREATE POLICY allow_all_sponsor_slots ON public.sponsor_slots FOR ALL USING (true) WITH CHECK (true);
  END IF;
END $$;

